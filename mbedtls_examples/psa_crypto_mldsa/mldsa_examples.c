static void ml_dsa_44_import_keypair_sign_verify_export_pubkey(void)
{
    printf("******** ML-DSA-44 ********\r\n");
    psa_status_t status = PSA_ERROR_CORRUPTION_DETECTED;
    psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
    psa_set_key_bits(&attr, PSA_ML_DSA_44_BITS);
    psa_set_key_algorithm(&attr, PSA_ALG_ML_DSA);
    psa_set_key_usage_flags(&attr, PSA_KEY_USAGE_SIGN_MESSAGE | PSA_KEY_USAGE_VERIFY_MESSAGE | PSA_KEY_USAGE_EXPORT);
    psa_set_key_type(&attr, PSA_KEY_TYPE_ML_DSA_KEY_PAIR);
    psa_set_key_lifetime(&attr, PSA_KEY_LIFETIME_FROM_PERSISTENCE_AND_LOCATION(PSA_KEY_PERSISTENCE_VOLATILE, PSA_KEY_LOCATION_LOCAL_STORAGE));

    psa_key_id_t key = PSA_KEY_ID_NULL;

    size_t key_pair_length = 0u;
    size_t public_key_length = 0u;

    uint8_t signature[PSA_MLDSA_SIGNATURE_SIZE(PSA_ML_DSA_44_BITS)] = { 0u };
    size_t signature_length = 0u;

    status = psa_import_key(&attr, mldsa_44_seed, sizeof(mldsa_44_seed), &key);
    print_result("Call psa_import_key()", status, PSA_SUCCESS);

    status = psa_sign_message(key, PSA_ALG_ML_DSA, input_message, input_message_length, signature, sizeof(signature), &signature_length);
    print_result("Call psa_sign_message()", status, PSA_SUCCESS);

    status = psa_verify_message(key, PSA_ALG_ML_DSA, input_message, input_message_length, signature, signature_length);
    print_result("Call psa_verify_message()", status, PSA_SUCCESS);

    memset(out_buffer, 0, sizeof(out_buffer));
    status = psa_export_key(key, out_buffer, sizeof(out_buffer), &key_pair_length);
    print_result("Call psa_export_key()", status, PSA_SUCCESS);

    status = 0 != memcmp(mldsa_44_seed, out_buffer, key_pair_length) ? PSA_ERROR_GENERIC_ERROR : PSA_SUCCESS;
    print_result("Key pair matches original seed value", status, PSA_SUCCESS);

    memset(out_buffer, 0, sizeof(out_buffer));
    status = psa_export_public_key(key, out_buffer, sizeof(out_buffer), &public_key_length);
    print_result("Call psa_export_public_key()", status, PSA_SUCCESS);

    status = 0 != memcmp(mldsa_44_public_key_expected, out_buffer, public_key_length) ? PSA_ERROR_GENERIC_ERROR : PSA_SUCCESS;
    print_result("Public key matches expected value", status, PSA_SUCCESS);

    status = psa_destroy_key(key);
    print_result("Call psa_destroy_key()", status, PSA_SUCCESS);
}

