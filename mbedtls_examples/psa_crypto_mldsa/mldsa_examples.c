int main(void)
{
    psa_status_t status;

    /* HW init */
    BOARD_InitHardware();

    printf(" * PSA ML-DSA example * \r\n\r\n");

    status = psa_crypto_init();

    if (status != PSA_SUCCESS)
    {
        print_result("Call psa_crypto_init()", status,  PSA_SUCCESS);
        goto exit;
    }

    /* Below are isolated cases in individual functions that showcase correct
     * setting of key attributes and usage of PSA for ML-DSA.
     *
     * *NOTE*
     * Errors in this example are intentionally non-fatal and no error handling
     * is added.
     */

    ml_dsa_44_import_keypair_sign_verify_export_pubkey();
    ml_dsa_44_import_keypair_sign_export_pubkey_verify();
    ml_dsa_44_import_invalid_keypair();

    ml_dsa_65_keygen_sign_verify();
    ml_dsa_65_keygen_sign_verify_ivalid_signature();

    ml_dsa_87_keygen_sign_verify();
    ml_dsa_87_keygen_sign_small_signature_buffer_size();

exit:

    if (status == PSA_SUCCESS)
    {
        mbedtls_psa_crypto_free();
    }

    printf("\r\n * Example End * \r\n\r\n");

    while(1)
    {
        GETCHAR();
    }

    return 0;
}
